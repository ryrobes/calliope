import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('./calliope/calliope.js', import.meta.url), 'utf8');
const functions = source.slice(source.indexOf('  function voiceTuningStorageKey('), source.indexOf('  function voiceTakes('));
const storage = new Map([['rvbbit-calliope-voice-tuning-v1',JSON.stringify({voice_id:'callie-voice',direction:'Callie delivery'})]]);
let agent = 'calliope';
const ctx = vm.createContext({VOICE_TUNING_KEY:'rvbbit-calliope-voice-tuning-v1',VOICE_TUNING_UI:true,chatAgent:()=>({key:agent}),localStorage:{getItem:key=>storage.get(key),setItem:(key,value)=>storage.set(key,value)}});
vm.runInContext(functions,ctx);
assert.equal(ctx.readVoiceTuning().voice_id,'callie-voice');
agent='semantic-architect';
assert.equal(ctx.readVoiceTuning().voice_id,'');
assert.equal(ctx.readVoiceTuning().direction,'');
assert.equal(ctx.voiceTuningRequestFields().tuning_agent_key,agent);
ctx.writeVoiceTuning({voice_id:'athena-custom',direction:'Measured'});
agent='signal-watch';assert.equal(ctx.readVoiceTuning().voice_id,'');
agent='calliope';assert.equal(ctx.readVoiceTuning().voice_id,'callie-voice');
agent='semantic-architect';assert.equal(ctx.readVoiceTuning().voice_id,'athena-custom');assert.equal(ctx.voiceTuningRequestFields().direction,'Measured');
console.log('Voice tuning: legacy Calliope preserved; agent voices and directions isolated.');
