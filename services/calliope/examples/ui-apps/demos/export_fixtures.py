"""One-time legacy fixture export; published apps never run the SQLite harness."""
import datetime as dt
import re
import sys
import tempfile
from pathlib import Path
from psycopg import sql
ROOT=Path(__file__).resolve().parents[5]
sys.path.insert(0,str(ROOT/'apps/calliope-canvas/business'))
from server import Store

def export():
    with tempfile.TemporaryDirectory() as temp:
        store=Store(Path(temp)/'legacy.sqlite')
        with store.connect() as db:
            tables=[dict(r) for r in db.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name<>'requests' ORDER BY rowid")]
            names={r['name']:'calliope_apps.demo_'+r['name'] for r in tables}
            statements=[]
            for table in tables:
                ddl=table['sql']
                ddl=re.sub(r'\bid INTEGER PRIMARY KEY\b','id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',ddl)
                ddl=re.sub(r'\bBLOB\b','bytea',ddl)
                ddl=re.sub(r'\bend\b','"end"',ddl)
                ddl=ddl.replace('CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ',1) if 'IF NOT EXISTS' not in ddl else ddl
                for name,new in sorted(names.items(),key=lambda p:-len(p[0])):
                    ddl=re.sub(r'\b'+name+r'\b',new,ddl)
                statements.append(ddl)
                rows=[dict(r) for r in db.execute('SELECT * FROM '+table['name'])]
                if rows:
                    def literal(k,v):
                        if k in ('scheduled_date','closing_date','expected_date','due') and isinstance(v,str):
                            try: return f"(current_date + {(dt.date.fromisoformat(v)-dt.date.today()).days})::text"
                            except ValueError: pass
                        return sql.Literal(v).as_string()
                    values=',\n'.join('('+','.join(literal(k,v) for k,v in row.items())+')' for row in rows)
                    cols=','.join(sql.Identifier(k).as_string() for k in rows[0])
                    statements.append(f"INSERT INTO {names[table['name']]} ({cols}) VALUES\n{values}\nON CONFLICT DO NOTHING")
                    if 'GENERATED BY DEFAULT AS IDENTITY' in ddl:
                        statements.append(f"SELECT setval(pg_get_serial_sequence('{names[table['name']]}','id'), (SELECT max(id) FROM {names[table['name']]}))")
            statements += ['CREATE TABLE IF NOT EXISTS calliope_apps.demo_schedule_lock(id integer PRIMARY KEY,revision bigint NOT NULL DEFAULT 0)', 'INSERT INTO calliope_apps.demo_schedule_lock(id) VALUES(1) ON CONFLICT DO NOTHING']
            return statements

if __name__=='__main__':
    Path(__file__).with_name('setup.sql').write_text('-- Fictional regression records, explicitly installed once. Existing rows are retained.\n\n'+';\n\n'.join(export())+';\n')
